import Foundation
import Testing
@testable import LaborKit

/// The listing and the app have to say the same thing, so the strings the reviewer
/// reads are assembled from the strings the screens render. These pin the join.
@Suite("Disclaimers")
struct DisclaimersTests {

    /// If the shipped disclaimer changes, the review notes change with it — that is
    /// the whole point of building them from one source.
    @Test func reviewNotesQuoteTheShippedDisclaimer() {
        #expect(Disclaimers.reviewNotes.contains(Disclaimers.measuredNotDiagnosed))
    }

    /// The claims a reviewer will check against the binary. Each is verifiable from
    /// the capability list rather than from intent.
    @Test func reviewNotesStateTheFactsReviewChecks() {
        let notes = Disclaimers.reviewNotes
        for claim in ["Data Not Collected", "cloudKitDatabase: .none", "start-to-start",
                      "no HealthKit", "does not diagnose"] {
            #expect(notes.localizedCaseInsensitiveContains(claim), "review notes must state: \(claim)")
        }
    }

    /// **App Store Connect's Notes for Review field holds 4,000 characters**, and the
    /// notes are assembled from a disclaimer that is itself edited for other reasons —
    /// so the limit has to be a failing test rather than something a person remembers.
    /// Overflowing it is silent: the field truncates on paste and the reviewer reads
    /// half an answer to a question Apple asked in writing.
    @Test func reviewNotesFitTheNotesForReviewField() {
        let count = Disclaimers.reviewNotes.count
        #expect(count <= 4000, "Notes for Review is 4,000 characters; these are \(count)")
    }

    /// The 2026-09-05 rejection was Guideline 2.1, and Apple asked six numbered
    /// questions with an instruction to put the answers in this field "for reference on
    /// future submissions". Each heading below is one of them; a later edit that trims
    /// the field back under the character limit must not do it by dropping an answer.
    @Test func reviewNotesAnswerEveryQuestionAppleAsked() {
        let notes = Disclaimers.reviewNotes
        for heading in ["WHAT IT IS AND WHO IT IS FOR", "ACCESS AND SETUP",
                        "EXTERNAL SERVICES", "REGIONAL DIFFERENCES",
                        "REGULATION AND THIRD-PARTY MATERIAL"] {
            #expect(notes.contains(heading), "review notes must still answer: \(heading)")
        }
        // The three sub-bullets under Apple's question 1, each of which this app
        // answers with "there is none" — stated rather than left to be inferred.
        for absence in ["No account", "no user-generated content", "no paid content"] {
            #expect(notes.localizedCaseInsensitiveContains(absence),
                    "review notes must state there is: \(absence)")
        }
    }

    /// App Review round 2 (2026-09-09) rejected 1.0 (5) under 2.1(a) — "unable to add
    /// Widgets" — because the notes listed WidgetKit among the frameworks and a reviewer
    /// went looking for a widget on an iPad. There is none; the one extension is the
    /// Live Activity. The app has since become an iPhone-and-iPad app (HL-058), and the
    /// notes say so; what they must never do again is name the framework that suggested
    /// a widget, or fail to say plainly that there is no widget. Both halves are pinned.
    @Test func reviewNotesDoNotSuggestAWidget() {
        let notes = Disclaimers.reviewNotes
        #expect(notes.contains("no Home Screen widget"), "review notes must say there is no widget")
        #expect(!notes.contains("WidgetKit"), "review notes must not name WidgetKit — a reviewer read it as a widget")
        // HL-058: the app runs on both; the notes say so instead of asking for an iPhone.
        #expect(notes.contains("iPhone and iPad"), "review notes must say the app runs on iPhone and iPad")
    }

    /// The banned register, checked against the app's own copy rather than trusted.
    /// Decision 0018 makes this the App Review line, not only a voice rule.
    @Test func nothingTheAppSaysUsesTheBannedRegister() {
        let shipped = [
            Disclaimers.measuredNotDiagnosed,
            Disclaimers.onDevice,
            Disclaimers.reviewNotes,
        ]
        for text in shipped {
            for banned in Disclaimers.neverSays {
                #expect(
                    !text.localizedCaseInsensitiveContains(banned),
                    "shipped copy must never contain \"\(banned)\""
                )
            }
        }
    }

    /// `docs/app-store-review-notes.txt` is what the submission checklist says to paste —
    /// the notes rendered, because the source is a literal with continuations and an
    /// interpolation. It was regenerated by hand and sat at its 2026-09-05 text through
    /// two rewrites of the source; Copilot caught it on #39. `render-review-notes.sh`
    /// now writes it and the gate checks it; this test is the other half — the file must
    /// equal the value Swift itself produces, so the renderer cannot drift either.
    @Test func renderedReviewNotesMatchTheSource() throws {
        let file = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .deletingLastPathComponent().deletingLastPathComponent()
            .deletingLastPathComponent()
            .appendingPathComponent("docs/app-store-review-notes.txt")
        let rendered = try String(contentsOf: file, encoding: .utf8)
        #expect(rendered == Disclaimers.reviewNotes,
                "docs/app-store-review-notes.txt is stale — run ./scripts/render-review-notes.sh")
    }
}
